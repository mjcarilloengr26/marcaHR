// Returns the translation for `text` in `language`, or `text` itself when the
// language is English or the string hasn't been translated yet.
export function translate(text, language) {
  if (!language || language === "en") return text;
  const dict = TRANSLATIONS[language];
  return (dict && dict[text]) || text;
}

export default TRANSLATIONS;
